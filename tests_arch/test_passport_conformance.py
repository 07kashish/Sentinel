"""Two implementations of one specification, required to agree.

WHY A SECOND IMPLEMENTATION AT ALL
-----------------------------------
`spec/execution-passport/vectors/` was generated by the Python code, so the
corpus passing against Python proves Python is self-consistent and nothing
else. An ambiguity in the specification only surfaces when something written
from the DOCUMENT rather than from the code disagrees.

It found one immediately. Python has arbitrary-precision integers and accepted
`2**53 + 1` happily; `verify.mjs` has one number type and refused it. Past 2^53
an IEEE-754 double cannot hold the value exactly, so the document round-trips
to a different number and its digest changes in a verifier the issuer does not
control. The Python canonicaliser was corrected to match, and both now refuse
it -- `test_an_integer_past_the_safe_range_is_refused` is that finding, kept.

THE CONTROL DISCIPLINE
----------------------
Every refusal assertion here is paired with the valid case, and the corpus size
is asserted before anything else. A conformance runner over an empty directory
exits successfully and reads exactly like one that checked everything -- which
is not hypothetical: the JS runner's module-main guard was wrong on Windows, so
it executed nothing, printed nothing and exited 0 the first time it was run.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

from sentinel.domain.passport import canonical_bytes, digest_of

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "execution-passport"
VECTORS = SPEC / "vectors"


def _load(directory: Path) -> list[dict]:
    return [
        json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(directory.rglob("*.json"))
    ]


VALID = _load(VECTORS / "valid")
MALICIOUS = _load(VECTORS / "malicious")


def _ids(vectors):
    return [v["name"] for v in vectors]


# ── the corpus exists ───────────────────────────────────────────────────────


def test_the_corpus_is_not_empty():
    """FIRST, because everything below is vacuous otherwise. A conformance run
    over an empty directory succeeds and looks identical to a complete one.
    """
    assert len(VALID) >= 5, f"only {len(VALID)} valid vectors"
    assert len(MALICIOUS) >= 8, f"only {len(MALICIOUS)} malicious vectors"


def test_every_vector_says_why_it_exists():
    """A vector without a reason becomes a vector nobody dares delete and
    nobody can evaluate.
    """
    for vector in VALID + MALICIOUS:
        assert len(vector["why"]) > 40, vector["name"]


# ── the reference implementation agrees with its own corpus ────────────────


@pytest.mark.parametrize("vector", VALID, ids=_ids(VALID))
def test_a_valid_vector_canonicalises_to_its_recorded_digest(vector):
    assert digest_of(vector["document"]) == vector["expect"]["digest"]


@pytest.mark.parametrize("vector", MALICIOUS, ids=_ids(MALICIOUS))
def test_a_malicious_vector_is_caught(vector):
    """Each is checked against the SPECIFIC defect it encodes, not merely that
    something went wrong. "It failed" is not evidence it failed for the reason
    claimed.
    """
    expected = set(vector["expect"]["defects"])
    assert expected, f"{vector['name']} expects no defect at all"

    if "not_canonical" in expected:
        with pytest.raises(ValueError):
            digest_of(vector["document"])
        return

    if "digest_mismatch" in expected:
        assert digest_of(vector["document"]) != vector["expect"]["digest"]

    if "missing_required_field" in expected:
        from sentinel.domain.passport import REQUIRED_FIELDS

        document = vector["document"]
        blank = [
            field
            for field in REQUIRED_FIELDS
            if not str(document.get(field, "")).strip()
        ]
        assert blank, "no required field is actually absent or empty"

    if "parent_digest_mismatch" in expected:
        commitment = vector["document"]["previous_passport_digest"]
        supplied = vector.get("parents", [])
        assert supplied, "the vector supplies no parent, so nothing can mismatch"
        assert all(digest_of(parent) != commitment for parent in supplied)

    if "parent_unverified" in expected:
        assert vector["document"]["previous_passport_digest"]
        assert not vector.get("parents")

    if "attestation_mismatch" in expected:
        assert (
            vector["expect"]["attestation_digest"] != digest_of(vector["document"])
        )


# ── the canonical form, checked directly ───────────────────────────────────


def test_key_order_in_the_source_file_does_not_change_the_digest():
    """§1 sorts keys, so input order is discarded by construction. This is why
    "keys in the wrong order" is NOT in the malicious corpus: the format makes
    it impossible rather than detectable.
    """
    document = VALID[0]["document"]
    reversed_order = dict(reversed(list(document.items())))

    assert list(reversed_order) != list(document)
    assert digest_of(reversed_order) == digest_of(document)


def test_non_ascii_is_emitted_as_utf8_and_not_escaped():
    """The bytes, checked directly. Comparing digests alone would pass against
    an implementation that escaped consistently -- consistently wrong is still
    incompatible with every other implementation.
    """
    raw = canonical_bytes({"agent_id": "agent:Аркадий"})

    assert "Аркадий".encode("utf-8") in raw
    # The ESCAPED spelling must be absent: six ASCII characters, backslash u
    # 0410, which is what `ensure_ascii=True` would have emitted instead.
    assert b"\\u0410" not in raw


def test_there_is_no_insignificant_whitespace():
    raw = canonical_bytes({"b": 1, "a": 2})

    assert raw == b'{"a":2,"b":1}'


def test_an_integer_past_the_safe_range_is_refused():
    """The one real disagreement the second implementation found. Kept as a
    test so the Python side cannot drift back to accepting it.
    """
    with pytest.raises(ValueError) as raised:
        digest_of({"risk_score": 2**53 + 1})

    assert "round trip" in str(raised.value)


def test_the_exact_safe_boundary_is_accepted():
    """Without this the bound could be implemented as any smaller limit, or as
    refusing all large integers, and every other test would still pass.
    """
    assert digest_of({"risk_score": 2**53 - 1})


# ── the two implementations agree ──────────────────────────────────────────


def _node() -> str | None:
    return shutil.which("node")


def test_the_independent_verifier_agrees_on_every_vector():
    """Runs `verify.mjs` over the whole corpus.

    Skips rather than passes when node is absent: a silent pass would leave the
    only cross-implementation check untested on machines without a runtime, and
    that check is the entire reason the second implementation exists.
    """
    node = _node()
    if node is None:
        pytest.skip("node not installed; reported rather than passed silently")

    result = subprocess.run(
        [node, str(SPEC / "verify.mjs"), "--vectors", str(VECTORS)],
        capture_output=True,
        text=True,
        cwd=str(ROOT),
    )

    # The output is asserted, not just the exit code. The runner's first
    # version had a broken module-main guard on Windows: it ran nothing,
    # printed nothing, and exited 0.
    assert "vectors agreed" in result.stdout, (
        f"the runner produced no verdict, so its exit code means nothing.\n"
        f"stdout: {result.stdout!r}\nstderr: {result.stderr!r}"
    )
    assert result.returncode == 0, result.stdout + result.stderr
    total = len(VALID) + len(MALICIOUS)
    assert f"{total}/{total} vectors agreed" in result.stdout


def test_both_implementations_compute_the_same_digest():
    """The load-bearing agreement. The runner above could pass while the JS
    digest function was broken -- e.g. if it echoed the claimed digest back --
    so the digests are compared directly here.
    """
    node = _node()
    if node is None:
        pytest.skip("node not installed; reported rather than passed silently")

    script = (
        # `pathToFileURL`, because an ESM import of a Windows drive path is
        # ERR_UNSUPPORTED_ESM_URL_SCHEME.
        "const {pathToFileURL} = await import('node:url');"
        "const m = await import(pathToFileURL(process.env.VERIFIER).href);"
        "const fs = await import('node:fs');"
        "const out = {};"
        # slice(1), not slice(2): under `-e` there is no script path in argv,
        # so the first user argument sits at index 1. slice(2) silently dropped
        # the alphabetically-first vector -- and the control assertion below
        # still passed, because the others were read.
        "for (const p of process.argv.slice(1)) {"
        "  const v = JSON.parse(fs.readFileSync(p, 'utf8'));"
        "  try { out[v.name] = m.digestOf(v.document); }"
        "  catch (e) { out[v.name] = 'REFUSED'; }"
        "}"
        "console.log(JSON.stringify(out));"
    )
    paths = [str(p) for p in sorted((VECTORS / "valid").rglob("*.json"))]
    result = subprocess.run(
        [node, "--input-type=module", "-e", script, "--", *paths],
        capture_output=True, text=True, cwd=str(ROOT),
        env={**os.environ, "VERIFIER": str(SPEC / "verify.mjs")},
    )
    assert result.returncode == 0, result.stderr

    from_js = json.loads(result.stdout)
    assert from_js, "control: the JS side returned nothing to compare"

    for vector in VALID:
        assert from_js[vector["name"]] == digest_of(vector["document"]), (
            f"{vector['name']}: the two implementations disagree, which means "
            f"the specification is ambiguous at this point"
        )


def test_the_independent_verifier_can_actually_fail():
    """A runner that reported success unconditionally would pass every test
    above. This hands it a vector it must reject.
    """
    node = _node()
    if node is None:
        pytest.skip("node not installed; reported rather than passed silently")

    script = (
        "const {pathToFileURL} = await import('node:url');"
        "const m = await import(pathToFileURL(process.env.VERIFIER).href);"
        "const r = m.verify({execution_id:'x'}, {claimedDigest:'0'.repeat(64)});"
        "console.log(JSON.stringify(r.defects.map(d => d.code)));"
    )
    result = subprocess.run(
        [node, "--input-type=module", "-e", script],
        capture_output=True, text=True, cwd=str(ROOT),
        env={**os.environ, "VERIFIER": str(SPEC / "verify.mjs")},
    )
    assert result.returncode == 0, result.stderr

    codes = set(json.loads(result.stdout))

    assert "digest_mismatch" in codes
    assert "missing_required_field" in codes
    assert "signature_unverified" in codes


# ── the specification describes what exists ────────────────────────────────


def test_the_spec_names_every_malicious_vector_it_lists():
    """Documentation drift, caught. The first draft of README.md listed three
    vectors that did not exist, which is the same defect class as a readiness
    document citing files that have moved.
    """
    readme = (SPEC / "README.md").read_text(encoding="utf-8")

    for vector in MALICIOUS:
        assert vector["name"] in readme, (
            f"{vector['name']} is in the corpus but not named in README.md"
        )


def test_the_spec_records_the_integer_bound():
    """The one correction the second implementation forced. If it is not in the
    document, a third implementation repeats the mistake.
    """
    readme = (SPEC / "README.md").read_text(encoding="utf-8")

    assert "2^53" in readme
    assert "verify.mjs" in readme


def test_the_verifier_has_no_third_party_dependencies():
    """An auditor should not have to install a package tree to check a
    passport. Every dependency is something else to trust, and the format's
    claim is that verification requires trusting nobody.
    """
    source = (SPEC / "verify.mjs").read_text(encoding="utf-8")
    imports = [
        line for line in source.splitlines()
        if line.startswith("import ") and " from " in line
    ]

    assert imports, "control: no imports found, so this test checks nothing"
    for line in imports:
        assert "'node:" in line, f"non-builtin dependency: {line}"
    assert not (SPEC / "package.json").exists()
    assert not (SPEC / "node_modules").exists()


def test_the_schema_matches_the_implementation():
    """A hand-written schema beside a dataclass drifts the first time a field is
    added, and drifts SILENTLY -- it still validates every document anybody
    happens to test with. `schema.json` is generated, and this fails if the two
    diverge.
    """
    from sentinel.domain.passport import ExecutionPassport

    schema = json.loads((SPEC / "schema.json").read_text(encoding="utf-8"))
    emitted = set(
        ExecutionPassport(
            execution_id="x",
            tenant_id="t",
            occurred_at="2026-01-01T00:00:00+00:00",
        ).as_document()
    )
    declared = set(schema["properties"])

    assert declared == emitted, (
        f"schema.json and the implementation disagree.\n"
        f"  only in schema: {sorted(declared - emitted)}\n"
        f"  only in code:   {sorted(emitted - declared)}"
    )


def test_the_schema_permits_unknown_fields():
    """`additionalProperties: false` would make the schema contradict the format
    it describes: section 5 requires unknown fields to be preserved and included
    in the digest, because a verifier that dropped them would compute a
    different digest than the signer did.
    """
    schema = json.loads((SPEC / "schema.json").read_text(encoding="utf-8"))

    assert schema["additionalProperties"] is True


def test_the_schema_bounds_integers():
    """The bound the second implementation forced. Absent here, a generator
    consuming this schema would emit values the canonicaliser refuses.
    """
    schema = json.loads((SPEC / "schema.json").read_text(encoding="utf-8"))
    integers = [
        (name, body)
        for name, body in schema["properties"].items()
        if body.get("type") == "integer"
    ]

    assert integers, "control: no integer field found, so this checks nothing"
    for name, body in integers:
        assert body["maximum"] == 2**53 - 1, name
        assert body["minimum"] == -(2**53 - 1), name


def test_the_schema_says_validation_is_not_verification():
    """Somebody will validate a passport against this schema and conclude it is
    genuine. The schema cannot check the canonical form, the digest, the
    signature or the chain, so it has to say so where they will read it.
    """
    schema = json.loads((SPEC / "schema.json").read_text(encoding="utf-8"))

    assert "NOT SUFFICIENT" in schema["$comment"]
