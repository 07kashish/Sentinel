"""Fail a container build on unapproved inputs, links or credential patterns.

Run against the context received by Docker, not an arbitrary developer checkout.
Only file names, rule names and fingerprints leave the scanner; never values.
This gate does not scan OS/dependency layers or prove absence of all secrets.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.scan_release_for_secrets import scan_bytes, WHEEL_ALLOWED_DATA  # noqa: E402

EXACT = frozenset({
    "Dockerfile", ".dockerignore", "requirements.lock", "docker-entrypoint.sh", "LICENSE",
    "config/default_policy.json", "evaluation/__init__.py", "evaluation/soft_prompt.py",
    "evaluation/artifacts/soft_prompt_model.pkl", "evaluation/artifacts/soft_prompt_model_card.json",
    "standard/execution-passport-v1/verify_passport.py",
    "standard/execution-passport-v1/verify_evidence_bundle.py",
    "standard/execution-passport-v1/witness_root.py",
}) | WHEEL_ALLOWED_DATA
FORBIDDEN_PARTS = frozenset({
    ".git", ".venv", "venv", "node_modules", "__pycache__", ".terraform",
    ".pytest_cache", ".mypy_cache", ".ruff_cache",
})
REQUIRED = frozenset({
    "sentinel/composition/container.py", "sentinel/application/tool_runner.py",
    "sentinel/domain/execution_binding.py", "sentinel/interface/cli.py",
    "sentinel/interface/http.py", "sentinel/infrastructure/default_policy.json",
    "sentinel/interface/console/index.html", "sentinel/interface/console/app.js",
    "sentinel/interface/console/app.css", "requirements.lock", "docker-entrypoint.sh",
})


def allowed(name: str) -> bool:
    path = PurePosixPath(name)
    if path.is_absolute() or ".." in path.parts:
        return False
    if any(part in FORBIDDEN_PARTS or part.startswith(".env") for part in path.parts):
        return False
    return name in EXACT or (
        path.suffix == ".py" and (
            name.startswith("sentinel/") or (len(path.parts) == 2 and path.parts[0] == "scripts")
        )
    )


def dockerignore(root: Path) -> str:
    # Literal paths avoid Docker wildcard-parent traversal differences between
    # builders. This manifest is reviewed when runtime source files are added.
    names = {name for name in EXACT if (root / name).is_file()}
    for directory in ("sentinel", "scripts"):
        names.update(p.relative_to(root).as_posix() for p in (root / directory).rglob("*.py")
                     if allowed(p.relative_to(root).as_posix()))
    return ("# Generated by scripts/check_container_context.py --root . --write-dockerignore\n"
            "# Default deny, literal runtime file allowlist; validated again inside Docker.\n**\n"
            + "".join("!" + name + "\n" for name in sorted(names)))


def inspect(root: Path, *, require_complete: bool = True) -> dict:
    findings = []
    scanned = 0
    if require_complete:
        findings.extend({"path": name, "rule": "required-input-missing"}
                        for name in sorted(REQUIRED) if not (root / name).is_file())
    for path in sorted(root.rglob("*")):
        name = path.relative_to(root).as_posix()
        if path.is_symlink():
            findings.append({"path": name, "rule": "symlink-refused"})
            continue
        if path.is_dir():
            continue
        if not path.is_file() or not allowed(name):
            findings.append({"path": name, "rule": "not-allowlisted"})
            continue
        if path.stat().st_size > 10_000_000:
            findings.append({"path": name, "rule": "oversized-input"})
            continue
        scanned += 1
        for finding in scan_bytes("container-context", name, path.read_bytes(), {}):
            findings.append({"path": name, "rule": finding.rule, "fingerprint": finding.fingerprint})
    return {"schema": "sentinel.container-context/v1", "scanned": scanned,
            "passed": not findings, "findings": findings}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--write-dockerignore", action="store_true")
    args = parser.parse_args()
    if not args.root.is_dir():
        print('{"passed": false, "reason": "context-directory-unavailable"}')
        return 2
    if args.write_dockerignore:
        (args.root / ".dockerignore").write_text(dockerignore(args.root))
        return 0
    result = inspect(args.root)
    print(json.dumps(result, sort_keys=True))
    return 0 if result["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
