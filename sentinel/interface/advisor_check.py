"""`sentinel-advisor-check`: prove the advisory model is reachable, from the operator's shell.

The pilot setup view can only say "configured"; whether the endpoint answers is
a separate fact, and the honest way to establish it is to make one real call
with a SYNTHETIC incident and record what came back. Nothing here can reach
triage: the advisor is advisory by architecture, and this command only reports.

Prints the endpoint HOST, the model name, availability and the first line of
the model's note. Never the token, never the full endpoint.
"""
from __future__ import annotations

import argparse
import sys
from types import MappingProxyType
from typing import Sequence, TextIO
from urllib.parse import urlsplit

from sentinel.composition.settings import ConfigurationError, Settings
from sentinel.infrastructure.model_advisor import HttpModelAdvisor
from sentinel.infrastructure.outbound import HardenedHttpClient, OutboundRefused, OutboundUnavailable

#: Invented facts, in the keys the advisor forwards (`_redact` drops the rest).
#: No tenant, no identifiers, nothing that happened.
SYNTHETIC_INCIDENT = MappingProxyType({
    "severity": "high",
    "priority": "P2",
    "incident_type": "credential_file_read",
    "description": "synthetic incident generated by sentinel-advisor-check: an agent read a credentials file; nothing happened",
    "matched_rules": ["credential-file-read"],
    "trust_level": "untrusted",
})


def list_models(settings: Settings, *, client: HardenedHttpClient | None = None) -> list[str]:
    """`GET {endpoint}/models` on an OpenAI-compatible provider; names only."""
    http = client or HardenedHttpClient()
    response = http.request(
        method="GET",
        url=f"{settings.advisor.endpoint.rstrip('/')}/models",
        headers={"Authorization": f"Bearer {settings.advisor.token}"},
        idempotent=True,
    )
    if response.status != 200:
        raise OutboundUnavailable(f"the provider returned HTTP {response.status} for /models")
    payload = response.json()
    names = [str(item.get("id", "")) for item in payload.get("data", []) if isinstance(item, dict)]
    return sorted(name for name in names if name)


def main(argv: Sequence[str] | None = None, *, out: TextIO | None = None,
         client: HardenedHttpClient | None = None, cli_run=None) -> int:
    parser = argparse.ArgumentParser(description="Make one real advisory call with a synthetic incident and report the outcome.")
    parser.add_argument("--list-models", action="store_true", help="list the model names the provider offers, then exit")
    args = parser.parse_args(argv)
    stream = out or sys.stdout
    try:
        settings = Settings.from_environment()
    except ConfigurationError as exc:
        stream.write(f"configuration is invalid: {exc}\n")
        return 78  # EX_CONFIG
    if settings.advisor.cli_command:
        from sentinel.infrastructure.cli_advisor import AntigravityCliAdvisor

        if args.list_models:
            stream.write("--list-models applies to an HTTP provider; for the CLI run `agy models`.\n")
            return 64  # EX_USAGE
        cli = AntigravityCliAdvisor(command=settings.advisor.cli_command, model=settings.advisor.model, home=settings.advisor.cli_home,
                                    **({"run": cli_run} if cli_run else {}))
        return _report(stream, "antigravity cli", settings.advisor.model, cli.advise(incident=SYNTHETIC_INCIDENT))
    if not settings.advisor.endpoint:
        stream.write("no advisory model is configured (neither SENTINEL_ADVISOR_CLI_COMMAND nor SENTINEL_ADVISOR_ENDPOINT is set); "
                     "Sentinel decides without one and says so in every evidence record.\n")
        return 3
    host = urlsplit(settings.advisor.endpoint).hostname or "?"
    if args.list_models:
        try:
            names = list_models(settings, client=client)
        except (OutboundRefused, OutboundUnavailable) as exc:
            stream.write(f"provider {host}: cannot list models: {exc}\n")
            return 1
        stream.write(f"provider {host}: {len(names)} models\n")
        for name in names:
            stream.write(f"  {name}\n")
        return 0
    advisor = HttpModelAdvisor(endpoint=settings.advisor.endpoint, token=settings.advisor.token,
                               model=settings.advisor.model, **({"client": client} if client else {}))
    return _report(stream, host, settings.advisor.model, advisor.advise(incident=SYNTHETIC_INCIDENT))


def _report(stream: TextIO, provider: str, model: str, advice) -> int:
    stream.write(f"provider {provider}, model {model}: {'answered' if advice.available else 'UNAVAILABLE'}\n")
    stream.write(f"  {advice.detail}\n")
    if advice.available:
        first_line = advice.reasoning.strip().splitlines()[0] if advice.reasoning.strip() else ""
        stream.write(f"  note: {first_line[:200]}\n")
        stream.write("  authority: none; priority stays a deterministic function of severity\n")
    return 0 if advice.available else 1

if __name__ == "__main__":
    raise SystemExit(main())
